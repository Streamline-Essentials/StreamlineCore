package singularity.updates;

import singularity.Singularity;
import singularity.configs.given.GivenConfigs;
import singularity.configs.given.MainConfigHandler;
import singularity.interfaces.ISingularityExtension;
import singularity.registry.ModuleRegistry;
import singularity.utils.MessageUtils;

import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.net.URL;
import java.net.URLDecoder;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.security.CodeSource;
import java.util.Locale;
import java.util.Properties;
import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledExecutorService;
import java.util.concurrent.TimeUnit;
import java.util.jar.JarFile;
import java.util.zip.ZipEntry;

/**
 * Keeps StreamlineCore itself up to date from the module registry
 * ({@code https://modules.drak.gg/api/v1/core/<target>}).
 *
 * <p>A check runs shortly after the platform is enabled and then every
 * {@code core-updates.check-interval-hours}. When the registry has a higher version for this
 * build's {@linkplain ISingularityExtension#getCoreTarget() target}, it is downloaded,
 * verified and kept in {@code <data folder>/updates/} under a name no plugin or mod loader
 * picks up; {@link CoreJarSwap} puts it in place of the running jar as the JVM exits, so the
 * new version runs from the next start. Nothing is replaced while the server runs: the
 * running jar's classes are still being loaded from it.</p>
 *
 * <p>{@code core-updates.enabled: false} or {@code no-internet: true} skip the check;
 * {@code core-updates.auto-install: false} only announces new versions.</p>
 */
public final class CoreUpdater {
    /** The resource mod builds carry their target in, generated by {@code mod-common/mod.gradle}. */
    public static final String TARGET_RESOURCE = "streamline-core-target.properties";

    /** Appended to staged jar names ({@code x.jar.update}), so no loader scanning a folder takes them. */
    static final String STAGED_SUFFIX = ".update";

    private static final long FIRST_CHECK_DELAY_SECONDS = 20;

    private static ScheduledExecutorService executor;
    private static ISingularityExtension platform;
    private static String target;
    private static final ModuleRegistry REGISTRY = new ModuleRegistry();

    /** The version staged for install at shutdown, or {@code null}. */
    private static volatile String stagedVersion;

    private CoreUpdater() {
    }

    /**
     * Starts the checks for {@code platform}. Does nothing when the platform has no core
     * target (game clients, dev runs of other platforms) or when already started.
     */
    public static synchronized void start(ISingularityExtension platform) {
        if (executor != null) return;
        String target;
        try {
            target = platform.getCoreTarget();
        } catch (Throwable e) {
            return;
        }
        if (target == null || target.isEmpty()) return;

        CoreUpdater.platform = platform;
        CoreUpdater.target = target.toLowerCase(Locale.ROOT);
        clearStaged();

        executor = Executors.newSingleThreadScheduledExecutor(runnable -> {
            Thread thread = new Thread(runnable, "Streamline-CoreUpdater");
            thread.setDaemon(true);
            return thread;
        });
        executor.schedule(CoreUpdater::scheduledCheck, FIRST_CHECK_DELAY_SECONDS, TimeUnit.SECONDS);
    }

    private static void scheduledCheck() {
        try {
            check();
        } catch (Throwable e) {
            MessageUtils.logWarning("Could not check for StreamlineCore updates: " + e.getMessage());
        }
        int hours = 0;
        try {
            hours = config().getCoreUpdatesIntervalHours();
        } catch (Throwable ignored) {
            // No config to read; check only once.
        }
        if (hours > 0 && ! executor.isShutdown()) executor.schedule(CoreUpdater::scheduledCheck, hours, TimeUnit.HOURS);
    }

    /**
     * Checks the registry now, on the calling thread, and stages a newer build when
     * {@code core-updates.auto-install} allows it.
     *
     * @return the newer version found, or {@code null} when up to date or checks are off
     */
    public static String check() {
        MainConfigHandler config = config();
        if (platform == null || ! config.isCoreUpdatesEnabled() || config.isNoInternet()) return null;

        String current = platform.getVersion();
        if (current == null || current.isEmpty()) {
            MessageUtils.logWarning("Skipping the StreamlineCore update check: the running version is unknown.");
            return null;
        }
        ModuleRegistry.CoreBuild latest = REGISTRY.coreNow(target);
        if (latest.getVersion().isEmpty() || ModuleRegistry.compareVersions(latest.getVersion(), current) <= 0) {
            MessageUtils.logDebug("StreamlineCore " + current + " is up to date (" + target + " latest: " + latest.getVersion() + ").");
            return null;
        }
        String version = latest.getVersion();
        if (version.equals(stagedVersion)) return version;

        if (! config.isCoreUpdatesAutoInstall()) {
            MessageUtils.logInfo("StreamlineCore " + version + " is available (running " + current
                    + "): https://modrinth.com/plugin/streamline");
            return version;
        }

        Path running = runningJar();
        if (running == null) {
            MessageUtils.logWarning("StreamlineCore " + version + " is available (running " + current
                    + "), but the running jar could not be found to replace; download it from https://modrinth.com/plugin/streamline");
            return version;
        }

        Path folder = updatesFolder();
        Path temp = REGISTRY.fetchCore(latest, folder);
        Path staged = folder.resolve(newJarName(running, current, version) + STAGED_SUFFIX);
        try {
            clearStaged();
            ModuleRegistry.move(temp, staged);
        } catch (IOException e) {
            ModuleRegistry.deleteQuietly(temp);
            throw new ModuleRegistry.RegistryException("Could not stage the update: " + e.getMessage(), e);
        }

        Path replacement = running.resolveSibling(newJarName(running, current, version));
        File fallback = platform.getCoreUpdateFolder();
        CoreJarSwap.schedule(running, staged, replacement, fallback == null ? null : fallback.toPath());
        stagedVersion = version;
        MessageUtils.logInfo("StreamlineCore " + version + " was downloaded (running " + current
                + ") and is installed when the server stops.");
        return version;
    }

    /** The version staged for install at shutdown, or {@code null}. */
    public static String getStagedVersion() {
        return stagedVersion;
    }

    private static MainConfigHandler config() {
        return GivenConfigs.getMainConfig();
    }

    private static Path updatesFolder() {
        return Singularity.resolveDataFolder(platform.getName(), platform).toPath().resolve("updates");
    }

    /** Deletes jars staged by an earlier run; one that is still newer is downloaded again. */
    private static void clearStaged() {
        Path folder = updatesFolder();
        if (! Files.isDirectory(folder)) return;
        try (DirectoryStream<Path> files = Files.newDirectoryStream(folder, "*.jar" + STAGED_SUFFIX)) {
            for (Path file : files) ModuleRegistry.deleteQuietly(file);
        } catch (IOException ignored) {
            // Leftovers are never loaded.
        }
        ModuleRegistry.deleteQuietly(folder.resolve("swap-helper.jar.tmp"));
    }

    /**
     * The running jar's name with its version replaced, so {@code StreamlineCore-Spigot-2.6.1.8.jar}
     * becomes {@code StreamlineCore-Spigot-2.6.1.9.jar}; a name without the version is kept.
     */
    static String newJarName(Path running, String current, String version) {
        String name = running.getFileName().toString();
        int at = name.lastIndexOf(current);
        if (at < 0) return name;
        return name.substring(0, at) + version + name.substring(at + current.length());
    }

    /**
     * The jar StreamlineCore runs from: the platform class's code source when it is a plain
     * jar file, otherwise (Forge/NeoForge union file systems) the jar in the plugins or mods
     * folder that carries this build's target. {@code null} in dev runs, which load classes
     * from directories.
     */
    static Path runningJar() {
        File addons = new File(gg.drak.thebase.storage.StorageUtils.getEnvironmentFolder(), Singularity.getAddonsFolderName(platform));

        Path fromCodeSource = codeSourceJar();
        if (fromCodeSource != null) {
            // Paper loads Spigot-mapped plugins from a remapped copy in plugins/.paper-remapped/;
            // the jar to replace is the original of the same name in plugins/.
            for (Path parent = fromCodeSource.getParent(); parent != null; parent = parent.getParent()) {
                if (parent.getFileName() != null && parent.getFileName().toString().equals(".paper-remapped")) {
                    Path original = addons.toPath().resolve(fromCodeSource.getFileName().toString());
                    return Files.isRegularFile(original) ? original : null;
                }
            }
            return fromCodeSource;
        }

        if (! addons.isDirectory()) return null;
        String prefix = ("StreamlineCore-" + target + "-").toLowerCase(Locale.ROOT);
        Path byName = null;
        try (DirectoryStream<Path> jars = Files.newDirectoryStream(addons.toPath(), "*.jar")) {
            for (Path jar : jars) {
                if (target.equalsIgnoreCase(targetOf(jar))) return jar;
                if (byName == null && jar.getFileName().toString().toLowerCase(Locale.ROOT).startsWith(prefix)) byName = jar;
            }
        } catch (IOException ignored) {
            // Treated as not found.
        }
        return byName;
    }

    private static Path codeSourceJar() {
        try {
            CodeSource source = platform.getClass().getProtectionDomain().getCodeSource();
            if (source == null || source.getLocation() == null) return null;
            URL location = source.getLocation();
            Path path;
            if ("file".equalsIgnoreCase(location.getProtocol())) {
                path = Paths.get(location.toURI());
            } else {
                // union:/C:/mods/x.jar%23123!/ or jar:file:/mods/x.jar!/ : the file before the separators.
                String raw = URLDecoder.decode(location.toString(), StandardCharsets.UTF_8.name());
                raw = raw.replaceFirst("^(union|jar|jrt|modjar):", "");
                int cut = raw.length();
                for (String separator : new String[]{"!", "#"}) {
                    int i = raw.indexOf(separator);
                    if (i >= 0) cut = Math.min(cut, i);
                }
                raw = raw.substring(0, cut);
                path = raw.startsWith("file:") ? Paths.get(URI.create(raw.replace(" ", "%20"))) : Paths.get(stripLeadingSlash(raw));
            }
            return Files.isRegularFile(path) && path.getFileName().toString().toLowerCase(Locale.ROOT).endsWith(".jar") ? path : null;
        } catch (Exception e) {
            return null;
        }
    }

    /** {@code /C:/mods/x.jar} is a URI path; Windows paths do not take the leading slash. */
    private static String stripLeadingSlash(String raw) {
        return raw.length() > 2 && raw.charAt(0) == '/' && raw.charAt(2) == ':' ? raw.substring(1) : raw;
    }

    /** The core target a jar declares in {@link #TARGET_RESOURCE}, or {@code null}. */
    static String targetOf(Path jar) {
        try (JarFile file = new JarFile(jar.toFile())) {
            ZipEntry entry = file.getEntry(TARGET_RESOURCE);
            if (entry == null) return null;
            Properties properties = new Properties();
            try (InputStream in = file.getInputStream(entry)) {
                properties.load(in);
            }
            return properties.getProperty("target");
        } catch (IOException e) {
            return null;
        }
    }

    /** Stops the scheduled checks; a staged update still installs at shutdown. */
    public static synchronized void stop() {
        if (executor != null) executor.shutdownNow();
    }
}
